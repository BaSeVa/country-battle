const FN = { sqrt: Math.sqrt, sin: Math.sin, cos: Math.cos, tan: Math.tan, exp: Math.exp, abs: Math.abs, log: Math.log, ln: Math.log };
const IDS = ['sqrt', 'sin', 'cos', 'tan', 'exp', 'abs', 'log', 'ln', 'pi', 'x', 'e'];
function compileExpr(src) {
  const s = String(src).toLowerCase().replace(/\s+/g, '').replace(/−/g, '-').replace(/π/g, 'pi').replace(/·|×/g, '*');
  let i = 0;
  const peek = () => s[i];
  function expr() { let a = term(); while (peek() === '+' || peek() === '-') { const op = s[i++]; const b = term(), A = a; a = op === '+' ? x => A(x) + b(x) : x => A(x) - b(x); } return a; }
  function term() {
    let a = unary();
    for (;;) {
      const c = peek();
      if (c === '*' || c === '/') { i++; const b = unary(), A = a; a = c === '*' ? x => A(x) * b(x) : x => A(x) / b(x); }
      else if (c !== undefined && /[a-z(0-9.]/.test(c)) { const b = pow(), A = a; a = x => A(x) * b(x); }
      else break;
    }
    return a;
  }
  function unary() { if (peek() === '-') { i++; const a = unary(); return x => -a(x); } if (peek() === '+') { i++; return unary(); } return pow(); }
  function pow() { const b = atom(); if (peek() === '^') { i++; const e = unary(); return x => Math.pow(b(x), e(x)); } return b; }
  function atom() {
    const c = peek();
    if (c === '(') { i++; const a = expr(); if (peek() !== ')') throw new Error('скобка'); i++; return a; }
    if (c !== undefined && /[0-9.]/.test(c)) { const j = i; while (i < s.length && /[0-9.]/.test(s[i])) i++; const v = parseFloat(s.slice(j, i)); if (isNaN(v)) throw new Error('число'); return () => v; }
    for (const id of IDS) if (s.startsWith(id, i)) {
      i += id.length;
      if (FN[id]) { const g = FN[id]; const a = unary(); return x => g(a(x)); }
      if (id === 'x') return x => x;
      if (id === 'pi') return () => Math.PI;
      if (id === 'e') return () => Math.E;
    }
    throw new Error('символ «' + (c || '') + '»');
  }
  const g = expr();
  if (i !== s.length) throw new Error('лишнее «' + s.slice(i) + '»');
  return x => { const v = g(x); return Number.isFinite(v) ? v : NaN; };
}
